// Generate both BASIC launchers' inline probe from the shared assembly.
// AI-assisted implementation, 2026-10-27.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { assembleAsmFile } from "./asm6502.mjs"

const src = path.dirname(fileURLToPath(import.meta.url))
export function updateFmProbe() {
  const probes = [2, 4].map(slot => assembleAsmFile(src, "vera_fm_detect.inc", slot, 0x300, ["FM_PRESENT = $02FF"]))
  const size = probes[0].length
  if (size !== probes[1].length || size > 0xF0) throw new Error("FM probe exceeds $0300-$03EF scratch area")
  const lines = [
    "500 FM = 0", "502 IF S = 0 THEN RETURN", "504 RESTORE",
    `506 IF S = 4 THEN FOR I = 1 TO ${size}:READ B:NEXT I`,
    `508 FOR I = 768 TO ${767 + size}:READ B:POKE I,B:NEXT I`,
    '510 CALL 768:FM = PEEK(767)',
    '512 IF FM = 1 THEN PRINT "STATUS: YM2151 (OPM) FM CHIP FOUND":RETURN',
    '514 PRINT "STATUS: NO YM2151 (OPM) FM CHIP FOUND":RETURN',
    '590 REM GENERATED BY SRC/UPDATE_FM_PROBE.MJS'
  ]
  let line = 600
  for (const bytes of probes) {
    for (let i = 0; i < bytes.length; i += 16) lines.push(`${line++} DATA ${Array.from(bytes.slice(i, i + 16)).join(",")}`)
  }
  for (const dir of ["veratest", "slideshow"]) {
    const file = path.join(src, dir, "startup.bas")
    const original = fs.readFileSync(file, "utf8")
    if (!/^500 FM = 0/m.test(original)) throw new Error(`Missing probe in ${file}`)
    const newline = original.includes("\r\n") ? "\r\n" : "\n"
    const updated = original.replace(/^500 FM = 0[\s\S]*$/m, lines.join(newline) + newline)
    if (updated !== original) fs.writeFileSync(file, updated)
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) updateFmProbe()
